"""HackerSlide 810 keyboard PCB: 53-key matrix (48 keys + 5-way D-pad), RP2040 scanner, USB HID to the module.

Usage: python3 keyboard_design.py [alps|dome] OUTDIR
  alps: Alps SKSWCFE010 tact switches (fab assembled)  dome: Keystone 5135 metal domes (hand placed)
"""
import sys

import kbd_layout as KL
from kigen import Design
from parts import C, R, fields


def build(variant='alps'):
    sw_fp = {'alps': 'hackerslide:SW_Alps_SKSWCFE010_3x2mm', 'dome': 'hackerslide:SW_Keystone_5135_Dome_7mm'}[variant]
    sw_fields = {'alps': fields('C255576', 'SKSWCFE010', 'Alps Alpine'),
                 'dome': fields('', '5135', 'Keystone Electronics', Note='metal dome, hand placed with Keystone 5200 spacer')}[variant]
    d = Design('keyboard' if variant == 'alps' else 'keyboard-5135', 'HackerSlide 810 keyboard (' + variant + ')',
               comments=['DRAFT - NEEDS HUMAN REVIEW. Generated by hardware/scripts/keyboard_design.py',
                         'Matrix COL2ROW: column driven, diode anode at switch, cathode to row.',
                         'Scanner: RP2040 USB HID (decision 0003). I2C1 + KB_INT kept for the I2C fallback.'])

    # ---- matrix -------------------------------------------------------------------------------------
    m = d.sheet('matrix', 'Key matrix (5 rows x 12 cols, row 4 = D-pad)', paper='A2',
                notes=['Each key: switch SWn + diode Dn (1N4148WS). Rows R0..R4 = RP2040 GPIO0..4, cols C0..C11 = GPIO5..16.',
                       'Key legends and positions: hardware/scripts/kbd_layout.py (shared with the top plate and enclosure).'])
    for i, (name, r, c, x, y) in enumerate(KL.keys(variant)):
        m.add(f'SW{i + 1}', 'hackerslide', 'KeySwitch', name, sw_fp, {'1': f'COL{c}', '2': f'K{r}_{c}'},
              fields=dict(sw_fields, Description=f'key "{name}" row {r} col {c}'))
        m.add(f'D{i + 1}', 'Diode', '1N4148WS', '1N4148WS', 'Diode_SMD:D_SOD-323', {'2': f'K{r}_{c}', '1': f'ROW{r}'},
              fields=fields('C2128', '1N4148WS', 'Changjiang'))

    # ---- MCU ----------------------------------------------------------------------------------------
    s = d.sheet('scanner', 'RP2040 scanner, flash, crystal, FPC to carrier', paper='A3',
                notes=['RP2040 minimal design follows the Raspberry Pi "Hardware design with RP2040" guide:',
                       '12 MHz crystal with 1k series R on XOUT, 27R USB series resistors, 1 uF on VREG_IN/VREG_VOUT.',
                       'KB_BOOT_N from the carrier pulls QSPI_SS low through 1k: enter USB bootloader from Linux.',
                       'FPC J1 pinout is mirrored 1:1 on the carrier (J9). Use a same-side-contact 20-pin 0.5 mm FFC.'])
    gp = {f'GPIO{n}': None for n in range(30)}
    for r in range(5):
        gp[f'GPIO{r}'] = f'ROW{r}'
    for c in range(12):
        gp[f'GPIO{5 + c}'] = f'COL{c}'
    gp['GPIO18'], gp['GPIO19'], gp['GPIO20'] = 'I2C_SDA', 'I2C_SCL', 'KB_INT'
    from kigen import get_symbol, sym_pins
    nets = {}
    pins = {p[1]: p[2] for p in sym_pins(get_symbol('MCU_RaspberryPi', 'RP2040'))}
    for num, name in pins.items():
        if name in gp or name.startswith('GPIO2') and '_ADC' in name:
            if gp.get(name):
                nets[num] = gp[name]
        elif name in ('IOVDD', 'USB_VDD', 'ADC_AVDD', 'VREG_IN'):
            nets[num] = '+3V3'
        elif name in ('DVDD', 'VREG_VOUT'):
            nets[num] = '+1V1'
        elif name in ('GND', 'TESTEN'):
            nets[num] = 'GND'
        else:
            nets[num] = {'RUN': 'KB_RST_N', 'USB_DP': 'USB_DP_MCU', 'USB_DM': 'USB_DM_MCU', 'QSPI_SS': 'QSPI_SS',
                         'QSPI_SD0': 'QSPI_SD0', 'QSPI_SD1': 'QSPI_SD1', 'QSPI_SD2': 'QSPI_SD2', 'QSPI_SD3': 'QSPI_SD3',
                         'QSPI_SCLK': 'QSPI_SCLK', 'XIN': 'XIN', 'XOUT': 'XOUT_R', 'SWCLK': 'SWCLK', 'SWD': 'SWDIO'}[name]
    s.add('U1', 'MCU_RaspberryPi', 'RP2040', 'RP2040', 'Package_DFN_QFN:QFN-56-1EP_7x7mm_P0.4mm_EP3.2x3.2mm', nets,
          fields=fields('C2040', 'RP2040', 'Raspberry Pi'))
    s.add('U2', 'Memory_Flash', 'W25Q128JVS', 'W25Q128JVSIQ', 'Package_SO:SOIC-8_5.3x5.3mm_P1.27mm',
          {'1': 'QSPI_SS', '6': 'QSPI_SCLK', '5': 'QSPI_SD0', '2': 'QSPI_SD1', '3': 'QSPI_SD2', '7': 'QSPI_SD3',
           '8': '+3V3', '4': 'GND'}, fields=fields('C97521', 'W25Q128JVSIQ', 'Winbond'))
    s.add('Y1', 'Device', 'Crystal_GND24', '12MHz', 'Crystal:Crystal_SMD_3225-4Pin_3.2x2.5mm',
          {'1': 'XIN', '3': 'XOUT', '2': 'GND', '4': 'GND'}, fields=fields('C9002', 'X322512MSB4SI', 'YXC'))
    R(s, 'R1', '1k', 'XOUT_R', 'XOUT', note='RP2040 crystal drive limiting')
    C(s, 'C1', '15p', 'XIN')
    C(s, 'C2', '15p', 'XOUT')
    R(s, 'R2', '27', 'USB_DP_MCU', 'USB_DP')
    R(s, 'R3', '27', 'USB_DM_MCU', 'USB_DM')
    R(s, 'R4', '10k', 'KB_RST_N', '+3V3', note='RUN pull-up; carrier can hold the RP2040 in reset')
    R(s, 'R5', '1k', 'QSPI_SS', 'KB_BOOT_N', note='BOOTSEL from carrier GPIO')
    R(s, 'R6', '10k', 'KB_INT', 'GND', note='keeps KB_INT low while RP2040 is unprogrammed')
    for i in range(6):
        C(s, f'C{10 + i}', '100n', '+3V3')
    C(s, 'C16', '100n', '+1V1')
    C(s, 'C17', '100n', '+1V1')
    C(s, 'C18', '1u', '+1V1')
    C(s, 'C19', '1u', '+3V3')
    C(s, 'C20', '10u', '+3V3')
    C(s, 'C21', '100n', '+3V3')  # flash
    s.add('TP1', 'Connector', 'TestPoint', 'SWCLK', 'TestPoint:TestPoint_Pad_D1.0mm', {'1': 'SWCLK'})
    s.add('TP2', 'Connector', 'TestPoint', 'SWDIO', 'TestPoint:TestPoint_Pad_D1.0mm', {'1': 'SWDIO'})
    s.add('TP3', 'Connector', 'TestPoint', 'GND', 'TestPoint:TestPoint_Pad_D1.0mm', {'1': 'GND'})
    s.add('TP4', 'Connector', 'TestPoint', '+3V3', 'TestPoint:TestPoint_Pad_D1.0mm', {'1': '+3V3'})
    fpc = {'1': 'GND', '2': '+3V3', '3': '+3V3', '4': 'GND', '5': 'USB_DP', '6': 'USB_DM', '7': 'GND',
           '8': 'I2C_SDA', '9': 'I2C_SCL', '10': 'KB_INT', '11': 'KB_RST_N', '12': 'KB_BOOT_N', '13': 'GND',
           '17': 'GND', '19': 'GND', '20': 'GND', 'MP': 'GND'}
    s.add('J1', 'Connector_Generic_MountingPin', 'Conn_01x20_MountingPin', 'FH12-20S-0.5SH',
          'Connector_FFC-FPC:Hirose_FH12-20S-0.5SH_1x20-1MP_P0.50mm_Horizontal', fpc,
          fields=fields('C596730', 'FH12-20S-0.5SH(55)', 'Hirose', Description='keyboard FPC to carrier J9; 14-16,18 spare'))
    return d


if __name__ == '__main__':
    variant, outdir = sys.argv[1], sys.argv[2]
    d = build(variant)
    probs = d.check()
    for p in probs:
        print('CHECK:', p)
    flagged = d.write(outdir)
    print('wrote', outdir, 'PWR_FLAG on', sorted(flagged))
