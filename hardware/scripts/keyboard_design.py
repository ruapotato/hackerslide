"""HackerSlide 810 keyboard PCB: 53 switches (48 keys + 5-way D-pad) on a TI TCA8418 I2C keypad scanner.

Revised after the 2026-11-24 audit (docs/audit-2026-11-24.md, section 10): the RP2040 USB scanner, its flash and
crystal are gone; the carrier no longer needs a USB hub.

Usage: python3 keyboard_design.py [alps|dome] OUTDIR
  alps: Alps SKSWCFE010 tact switches (fab assembled)  dome: Keystone 5135 metal domes (hand placed)
"""
import sys

import kbd_layout as KL
from carrier_design import KB_FPC
from kigen import Design
from parts import C, R, TP, fields


def build(variant='alps'):
    sw_fp = {'alps': 'hackerslide:SW_Alps_SKSWCFE010_3x2mm', 'dome': 'hackerslide:SW_Keystone_5135_Dome_7mm'}[variant]
    sw_fields = {'alps': fields('C255576', 'SKSWCFE010', 'Alps Alpine'),
                 'dome': fields('', '5135', 'Keystone Electronics', Note='metal dome, hand placed, not soldered')}[variant]
    d = Design('keyboard' if variant == 'alps' else 'keyboard-5135', 'HackerSlide 810 keyboard (' + variant + ')',
               comments=['DRAFT - NEEDS HUMAN REVIEW. Generated by hardware/scripts/keyboard_design.py',
                         'Scanner: TI TCA8418 (I2C 0x34, mainline tca8418_keypad). 6 rows x 10 columns electrical matrix.',
                         'The TCA8418 drives columns low and reads pulled-up rows: each diode conducts ROW -> COL.'])

    # ---- matrix -------------------------------------------------------------------------------------
    m = d.sheet('matrix', 'Key matrix (6 rows x 10 columns electrical; 4 x 12 keys + D-pad physical)', paper='A2',
                notes=['Each key: switch SWn in series with diode Dn (1N4148WS), anode toward the row. Diodes are kept on purpose:',
                       'without them the TCA8418 reports a phantom key for three-key combinations (TI SCPS215G 9.1.1).',
                       'Electrical map (kbd_layout.matrix_pos): rows 0-3 = physical rows, physical columns 0-9;',
                       'row 4 = physical column 10 (COL0-3) and column 11 (COL4-7); row 5 = D-pad (COL0-4).',
                       'Both Space switches share one matrix position (ROW3/COL6): one key, one diode (K3).',
                       'Assembly (K2): the switches allow two reflows at most and must not be washed.'])
    seen = {}
    for i, (name, pr, pc, x, y) in enumerate(KL.keys(variant)):
        r, c = KL.matrix_pos(pr, pc)
        knode = f'K{r}_{c}'
        # dome variant, D-pad: the foot pads of neighbouring domes merge, so they carry the shared row net (K8)
        if variant == 'dome' and pr == 4:
            pads = {'1': f'ROW{r}', '2': knode}
            dio = {'2': knode, '1': f'COL{c}'}
        else:
            pads = {'1': f'COL{c}', '2': knode}
            dio = {'2': f'ROW{r}', '1': knode}
        m.add(f'SW{i + 1}', 'hackerslide', 'KeySwitch', name, sw_fp, pads,
              fields=dict(sw_fields, Description=f'key "{name}" matrix row {r} col {c}'))
        if (r, c) in seen:
            continue                                    # second Space switch: parallel to the first, same diode
        seen[(r, c)] = i
        m.add(f'D{i + 1}', 'Diode', '1N4148WS', '1N4148WS', 'Diode_SMD:D_SOD-323', dio,
              fields=fields('C2128', '1N4148WS', 'Changjiang'))

    # ---- scanner ------------------------------------------------------------------------------------
    s = d.sheet('scanner', 'TCA8418 keypad scanner, FPC to carrier', paper='A3',
                notes=['TCA8418RTW pins 1-8 = ROW7..ROW0, 9-18 = COL0..COL9 (TI SCPS215G pin table).',
                       'VCC 3.3 V: with a diode in series the row low level is VF + VOL, too high for 1.8 V logic.',
                       'Unused ROW6/ROW7 are tied to VCC through 100k as the datasheet asks.',
                       'The pins are rated 2 kV HBM only: U2 clamps the cable signals, and the top plate copper is grounded',
                       'through the plated mounting holes H1-H10.',
                       'FPC J1 carries the same pin numbers as carrier J9 (see the carrier keyboard_link sheet).'])
    nets = {'22': 'I2C_B_SDA', '23': 'I2C_B_SCL', '24': 'KB_INT_N', '20': 'KB_RST_N', '21': '+3V3', '19': 'GND', '25': 'GND'}
    for r in range(6):
        nets[str(8 - r)] = f'ROW{r}'
    nets['2'], nets['1'] = 'ROW6_NC', 'ROW7_NC'
    for c in range(10):
        nets[str(9 + c)] = f'COL{c}'
    s.add('U1', 'hackerslide', 'TCA8418RTW', 'TCA8418RTWR', 'Package_DFN_QFN:WQFN-24-1EP_4x4mm_P0.5mm_EP2.45x2.45mm', nets,
          fields=fields('C138713', 'TCA8418RTWR', 'Texas Instruments'))
    R(s, 'R1', '100k', 'ROW6_NC', '+3V3')
    R(s, 'R2', '100k', 'ROW7_NC', '+3V3')
    R(s, 'R3', '10k', 'KB_INT_N', '+3V3', note='open-drain interrupt (also pulled up on the carrier)')
    R(s, 'R4', '10k', 'KB_RST_N', '+3V3')
    C(s, 'C1', '100n', '+3V3')
    C(s, 'C2', '1u', '+3V3')
    s.add('U2', 'Power_Protection', 'TPD4E05U06DQA', 'TPD4E05U06DQAR', 'Package_SON:USON-10_2.5x1.0mm_P0.5mm',
          {'1': 'I2C_B_SDA', '2': 'I2C_B_SCL', '4': 'KB_INT_N', '5': 'KB_RST_N', '3': 'GND', '8': 'GND'},
          fields=fields('C138714', 'TPD4E05U06DQAR', 'Texas Instruments', Description='ESD clamp on the cable signals'))
    s.add('J1', 'Connector_Generic_MountingPin', 'Conn_01x08_MountingPin', 'FH34SRJ-8S-0.5SH',
          'hackerslide:Hirose_FH34SRJ-8S-0.5SH_1x08-1MP_P0.50mm_Horizontal', dict(KB_FPC),
          fields=fields('C88372', 'FH34SRJ-8S-0.5SH(50)', 'Hirose', Description='keyboard FPC to carrier J9, 1.0 mm high'))
    for i in range(len(KL.PLATE_HOLES)):
        s.add(f'H{i + 1}', 'Mechanical', 'MountingHole_Pad', 'M1.6', 'hackerslide:MountingHole_M1.6_Pad', {'1': 'GND'},
              in_bom=False)
    TP(s, 'TP1', 'I2C_B_SDA')
    TP(s, 'TP2', 'I2C_B_SCL')
    TP(s, 'TP3', 'GND')
    TP(s, 'TP4', '+3V3')
    return d


if __name__ == '__main__':
    variant, outdir = sys.argv[1], sys.argv[2]
    d = build(variant)
    probs = d.check()
    for p in probs:
        print('CHECK:', p)
    flagged = d.write(outdir)
    print('wrote', outdir, 'PWR_FLAG on', sorted(flagged))
