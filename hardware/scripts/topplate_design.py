"""Keyboard top plate: a bare 0.8 mm PCB used as a mechanical plate (KeebDeck-style).

Keycap tops poke through rectangular cut-outs; each keycap's flange sits under the plate, so the plate holds the
caps captive over the switches.  Silkscreen carries the Fn-layer legends.  No electrical parts.
Usage: python3 topplate_design.py OUTDIR [--pcb]
"""
import os
import sys

import kbd_layout as KL
from kigen import Design
from keyboard_pcb import TOP_PLATE_HOLES


def build_sch():
    d = Design('keyboard-topplate', 'HackerSlide 810 keyboard top plate',
               comments=['Mechanical PCB, no circuit. Generated by hardware/scripts/topplate_design.py',
                         'Holes match the keyboard PCB (keyboard_pcb.TOP_PLATE_HOLES).'])
    s = d.sheet('plate', 'Top plate mounting holes', paper='A4',
                notes=['M1.6 screws through plate, printed spacer frame and keyboard PCB into the tray.'])
    for i in range(len(TOP_PLATE_HOLES)):
        s.add(f'H{i + 1}', 'Mechanical', 'MountingHole', 'M1.6', 'hackerslide:MountingHole_M1.6_NPTH', {},
              in_bom=False)
    return d


def cutouts(variant='alps'):
    """Plate openings: one per key (Space x2 merged), one per D-pad key."""
    c = KL.CAP
    hw, hh = c['top_w'] / 2 + KL.PLATE_HOLE_CLEAR, c['top_h'] / 2 + KL.PLATE_HOLE_CLEAR
    out = []
    keys = [k for k in KL.keys(variant) if k[1] < 4]
    space = [k for k in keys if k[0] == 'Space']
    for (name, r, col, x, y) in keys:
        if name == 'Space':
            continue
        out.append((x - hw, y - hh, x + hw, y + hh))
    if space:
        xs = [k[3] for k in space]
        y = space[0][4]
        out.append((min(xs) - hw, y - hh, max(xs) + hw, y + hh))
    d = {'alps': 2.4, 'dome': 2.9}[variant]   # D-pad cap top half-size
    for i in range(5):
        x, y = KL.dpad_center(i, variant)
        out.append((x - d, y - d, x + d, y + d))
    return out


def build_pcb(bdir):
    import pcbnew
    from pcbgen import Board, set_project_rules
    B = Board(os.path.join(bdir, 'netlist.json'), layers=2, thickness=0.8)
    B.outline(0, 0, KL.BOARD_W, KL.BOARD_H, r=1.5, cutouts=cutouts())
    for i, (x, y) in enumerate(TOP_PLATE_HOLES):
        B.place(f'H{i + 1}', x, y)
    for (name, r, c, x, y) in KL.keys():
        if r < 4:
            fn = KL.FN_LEGENDS[r][c]
            if fn:
                B.text(fn, x + KL.CAP['top_w'] / 2 - 0.3, y - KL.CAP['top_h'] / 2 - 0.45, pcbnew.F_SilkS, 0.6)
    B.text('HackerSlide 810 top plate rev 0.1', KL.BOARD_W / 2 + 20, KL.BOARD_H - 0.45, pcbnew.B_SilkS, 0.6, mirror=True)
    path = B.save(os.path.join(bdir, 'keyboard-topplate.kicad_pcb'))
    set_project_rules(path.replace('.kicad_pcb', '.kicad_pro'),
                      {'min_copper_edge_clearance': 0.3, 'min_text_height': 0.6}, [{'name': 'Default'}], [])
    return path


if __name__ == '__main__':
    out = sys.argv[1]
    if '--pcb' in sys.argv:
        print(build_pcb(out))
    else:
        d = build_sch()
        d.write(out)
        print('wrote', out)
