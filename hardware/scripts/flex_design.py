"""Keyboard flex cable: our own 1-layer flex circuit between carrier J9 and keyboard J1 (David, 2026-11-24).

Usage: python3 flex_design.py OUTDIR          writes the schematic, then the board (needs pcbnew)

Why a flex circuit: the cable makes a rolling loop of about 1.5-1.9 mm radius every time the slider moves.  Stock
0.5 mm FFC is 0.22-0.27 mm thick and rated at 5-10 mm bend radius (Molex Premo-Flex datasheet); a 0.07 mm flex is
inside JLCPCB's own guidance for repeated bending (radius >= 10-15 x thickness, i.e. about 1 mm).
Order as: 1 layer, 0.07 mm, 18 um copper, yellow coverlay, ENIG, PI stiffener 0.225 mm on the back of both ends
(4 mm long).  See bom/fab-orders.md.  Flex life at this radius is NOT rated by the fab: cycle-test it on the fit mule.

Design rules for the moving part: one copper layer, traces straight and parallel, no vias, no pads, no stiffener,
no silkscreen between the two ends.
"""
import os
import sys

from carrier_design import KB_FPC
from kigen import Design

N = 8
W = 0.5 * (N - 1) + 1.0       # 4.5 mm (Hirose FH34 catalogue, dimension G)
# Length along the cable path, mm (mechanical/src/config.py FPC_LEN re-derives this and asserts it matches):
LENGTH = 73.0
TRACE = 0.3


def build_sch():
    d = Design('keyboard-flex', 'HackerSlide 810 keyboard flex cable',
               comments=['DRAFT - NEEDS HUMAN REVIEW. Generated by hardware/scripts/flex_design.py',
                         '1-layer flex, 0.07 mm, 4.5 x %.0f mm. P1 plugs into carrier J9, P2 into keyboard J1.' % LENGTH,
                         'Finger k of P1 = carrier J9 pin k = keyboard J1 pin k (straight traces).'])
    s = d.sheet('flex', 'Straight 8-way flex', paper='A4',
                notes=['P2 is the same footprint turned 180 degrees, so its pad numbers run the other way:',
                       'P2 pad k carries the signal of P1 pad 9-k.  The traces are straight; nothing crosses.'])
    sig = {k: v for k, v in KB_FPC.items() if k != 'MP'}
    # +3V3 and GND each appear on two fingers; keep the four conductors separate on the cable
    names = {k: f'{v}_{k}' if v in ('GND', '+3V3') else v for k, v in sig.items()}
    s.add('P1', 'Connector_Generic', 'Conn_01x08', 'to carrier J9', 'hackerslide:FPC_Fingers_1x08_P0.5mm_FH34',
          {k: names[k] for k in sig}, in_bom=False)
    s.add('P2', 'Connector_Generic', 'Conn_01x08', 'to keyboard J1', 'hackerslide:FPC_Fingers_1x08_P0.5mm_FH34',
          {str(N + 1 - int(k)): names[k] for k in sig}, in_bom=False)
    return d


def build_pcb(bdir):
    import pcbnew
    from pcbgen import Board, set_project_rules
    MM = pcbnew.FromMM
    B = Board(os.path.join(bdir, 'netlist.json'), layers=2, thickness=0.07)
    B.outline(-W / 2, 0, W / 2, LENGTH, r=0.2)
    B.place('P1', 0, 0, 0, 'F')
    B.place('P2', 0, LENGTH, 180, 'F')
    for pad in B.fps['P1'].Pads():
        x = pad.GetPosition().x
        other = [p for p in B.fps['P2'].Pads() if p.GetPosition().x == x][0]
        assert other.GetNetname() == pad.GetNetname(), (pad.GetNumber(), other.GetNumber())
        t = pcbnew.PCB_TRACK(B.b)
        t.SetStart(pad.GetPosition()); t.SetEnd(other.GetPosition())
        t.SetWidth(MM(TRACE)); t.SetLayer(pcbnew.F_Cu); t.SetNet(pad.GetNet())
        B.b.Add(t)
    B.text('CARRIER J9', 0, 7.5, pcbnew.F_SilkS, 0.6, rot=90)
    B.text('KEYBOARD J1', 0, LENGTH - 8.0, pcbnew.F_SilkS, 0.6, rot=90)
    B.text('1-layer flex 0.07 mm, 18 um Cu, ENIG. PI stiffener 0.225 mm on the BACK of both ends (4 mm).',
           8.0, LENGTH / 2, pcbnew.Cmts_User, 0.8, rot=90)
    B.text('Moving section: no vias, pads, stiffener or silkscreen between y = 12 and y = %.0f.' % (LENGTH - 12),
           10.0, LENGTH / 2, pcbnew.Cmts_User, 0.8, rot=90)
    path = B.save(os.path.join(bdir, 'keyboard-flex.kicad_pcb'))
    set_project_rules(path.replace('.kicad_pcb', '.kicad_pro'),
                      {'min_clearance': 0.09, 'min_track_width': 0.09, 'min_copper_edge_clearance': 0.2},
                      [{'name': 'Default', 'clearance': 0.15, 'track_width': TRACE}], [])
    return path


if __name__ == '__main__':
    out = sys.argv[1]
    build_sch().write(out)
    print(build_pcb(out))
